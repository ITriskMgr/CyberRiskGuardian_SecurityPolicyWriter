# ------------------------------------------------------------------ low-level helpers
def _cap(s: str) -> str:
    return s[:1].upper() + s[1:] if s else s


def _shade(cell, hex_fill: str) -> None:
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_fill)
    tcPr.append(shd)


def _field(paragraph, instr: str, placeholder: str = "") -> None:
    run = paragraph.add_run()
    b = OxmlElement("w:fldChar"); b.set(qn("w:fldCharType"), "begin")
    i = OxmlElement("w:instrText"); i.set(qn("xml:space"), "preserve"); i.text = instr
    s = OxmlElement("w:fldChar"); s.set(qn("w:fldCharType"), "separate")
    t = OxmlElement("w:t"); t.text = placeholder
    e = OxmlElement("w:fldChar"); e.set(qn("w:fldCharType"), "end")
    for el in (b, i, s, t, e):
        run._r.append(el)


def _repeat_header(row) -> None:
    trPr = row._tr.get_or_add_trPr()
    h = OxmlElement("w:tblHeader"); h.set(qn("w:val"), "true")
    trPr.append(h)


def _no_split(row) -> None:
    trPr = row._tr.get_or_add_trPr()
    c = OxmlElement("w:cantSplit"); c.set(qn("w:val"), "true")
    trPr.append(c)


def _text_with_placeholders(paragraph, text: str, bold=False, size=None, color=None) -> None:
    pos = 0
    for m in PH_RE.finditer(text):
        if m.start() > pos:
            r = paragraph.add_run(text[pos:m.start()]); r.bold = bold
            if size: r.font.size = size
            if color: r.font.color.rgb = color
        r = paragraph.add_run(m.group(0)); r.bold = True
        r.font.highlight_color = WD_COLOR_INDEX.YELLOW
        if size: r.font.size = size
        pos = m.end()
    if pos < len(text):
        r = paragraph.add_run(text[pos:]); r.bold = bold
        if size: r.font.size = size
        if color: r.font.color.rgb = color


def _table(doc, headers, rows, widths_cm, font_pt=9, header_fill="0B4F6C"):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    hdr = t.rows[0]
    _repeat_header(hdr)
    for i, h in enumerate(headers):
        c = hdr.cells[i]
        c.width = Cm(widths_cm[i])
        _shade(c, header_fill)
        p = c.paragraphs[0]
        r = p.add_run(h); r.bold = True; r.font.size = Pt(font_pt); r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
    for i, w in enumerate(widths_cm):
        t.columns[i].width = Cm(w)
    for row in rows:
        cells = t.add_row()
        _no_split(cells)
        for i, val in enumerate(row):
            c = cells.cells[i]
            c.width = Cm(widths_cm[i])
            p = c.paragraphs[0]
            _text_with_placeholders(p, "" if val is None else str(val), size=Pt(font_pt))
    return t


def _kv_table(doc, pairs, widths=(5.0, 11.5)):
    t = doc.add_table(rows=0, cols=2)
    t.style = "Table Grid"
    t.autofit = False
    t.columns[0].width, t.columns[1].width = Cm(widths[0]), Cm(widths[1])
    for k, v in pairs:
        row = t.add_row()
        _no_split(row)
        a, b = row.cells
        a.width, b.width = Cm(widths[0]), Cm(widths[1])
        _shade(a, "E8EEF2")
        ra = a.paragraphs[0].add_run(k); ra.bold = True; ra.font.size = Pt(9)
        _text_with_placeholders(b.paragraphs[0], str(v), size=Pt(9))
    return t


def _base_document(lang: str):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.59), Cm(27.94)
    sec.orientation = WD_ORIENT.PORTRAIT
    sec.left_margin = sec.right_margin = Cm(2.3)
    sec.top_margin, sec.bottom_margin = Cm(2.2), Cm(2.0)
    st = doc.styles
    normal = st["Normal"]
    normal.font.name = "Calibri"
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    normal.font.size = Pt(10.5)
    normal.font.color.rgb = INK
    normal.paragraph_format.space_after = Pt(5)
    normal.paragraph_format.line_spacing = 1.12
    for name, size, color, before in (("Title", 22, INK, 0), ("Heading 1", 14, ACCENT, 16), ("Heading 2", 11.5, ACCENT, 10)):
        s = st[name]
        s.font.name = "Calibri"; s.font.size = Pt(size); s.font.bold = True; s.font.color.rgb = color
        rpr = s.element.get_or_add_rPr()
        fonts = rpr.find(qn("w:rFonts"))
        if fonts is None:
            fonts = OxmlElement("w:rFonts"); rpr.append(fonts)
        for a in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
            fonts.set(qn(a), "Calibri")
        for a in ("w:asciiTheme", "w:hAnsiTheme", "w:cstheme", "w:eastAsiaTheme"):
            if fonts.get(qn(a)) is not None:
                del fonts.attrib[qn(a)]
        s.paragraph_format.space_before = Pt(before)
        s.paragraph_format.space_after = Pt(6)
        s.paragraph_format.keep_with_next = True
    # Title style in python-docx default template has a bottom border; keep it subtle
    doc.core_properties.language = "fr-CA" if lang == "fr" else "en-CA"
    zoom = doc.settings.element.find(qn("w:zoom"))
    if zoom is not None and zoom.get(qn("w:percent")) is None:
        zoom.set(qn("w:percent"), "100")
    return doc


def _header_footer(doc, left: str, lang: str, version: str, classification: str):
    lab = L[lang]
    sec = doc.sections[0]
    hp = sec.header.paragraphs[0]
    hp.text = ""
    r = hp.add_run(left); r.font.size = Pt(8.5); r.font.color.rgb = GREY
    hp.add_run("\t\t")
    r2 = hp.add_run(lab["draft"]); r2.bold = True; r2.font.size = Pt(8.5); r2.font.color.rgb = RED
    fp = sec.footer.paragraphs[0]
    fp.text = ""
    r = fp.add_run(f"{lab['classification']}: {classification} · {lab['version']} {version}\t\t{lab['page']} ")
    r.font.size = Pt(8.5); r.font.color.rgb = GREY
    _field(fp, "PAGE", "1")
    r = fp.add_run(f" {lab['of']} "); r.font.size = Pt(8.5); r.font.color.rgb = GREY
    _field(fp, "NUMPAGES", "1")


def _draft_banner(doc, lang):
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    c = t.rows[0].cells[0]
    _shade(c, "FBEAEA")
    p = c.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(L[lang]["draft"]); r.bold = True; r.font.size = Pt(13); r.font.color.rgb = RED


# ------------------------------------------------------------------ policy document
def render_policy(body: dict, meta: dict | None = None) -> bytes:
    meta = meta or {}
    lang = body["language"]
    lab = L[lang]
    doc = _base_document(lang)
    _header_footer(doc, f"{body['organization']} — {body['policy_id']}", lang, body["version"], body["classification"])
    cp = doc.core_properties
    cp.title, cp.subject = body["title"], body["policy_id"]
    cp.identifier = f"{body['policy_id']}|{meta.get('document_uuid', '')}|v{body['version']}|{lang}"
    cp.version, cp.category = body["version"], "Information security policy — DRAFT"
    cp.keywords = f"policy_code={body['policy_code']}; library={body['library_version']}; schema={body['schema']}"
    cp.author = APP_NAME
    cp.comments = lab["disclaimer"][:250]

    p = doc.add_paragraph(style="Title")
    p.add_run(body["title"])
    sub = doc.add_paragraph()
    r = sub.add_run(f"{body['organization']}  ·  {body['policy_id']}  ·  {body['level_label']}")
    r.font.size = Pt(11); r.font.color.rgb = GREY
    _draft_banner(doc, lang)
    doc.add_paragraph()

    doc.add_heading(lab["doc_control"], level=2)
    gen_date = body["generated_at"][:10]
    _kv_table(doc, [
        (lab["doc_id"], body["policy_id"]), (lab["version"], body["version"]), (lab["status"], lab["status_v"]),
        (lab["classification"], body["classification"]), (lab["owner"], _cap(body["owner"])), (lab["approver"], _cap(body["approver"])),
        (lab["parent"], f"{body['parent_policy_id']} — {body['parent_title']}" if body.get("parent_policy_id") else "—"),
        (lab["review_cycle"], body["review_cycle"]), (lab["approval_date"], lab["set_on_approval"]),
        (lab["effective"], lab["set_on_approval"]), (lab["next_review"], lab["set_on_approval"]),
        (lab["language"], lab["lang_name"]),
        (lab["generated"], f"{APP_NAME} {APP_VERSION} · library {body['library_version']}"
                           + (f" · AI: {meta['model']}" if meta.get("model") else "")),
        (lab["generated_on"], gen_date),
    ])
    doc.add_heading(lab["revision"], level=2)
    _table(doc, lab["rev_cols"], [[body["version"], gen_date, lab["rev_desc"], lab["author_tbd"]]], [2.2, 2.6, 8.4, 3.3])
    doc.add_heading(lab["approvals"], level=2)
    _table(doc, lab["appr_cols"], [[lab["approver"], _cap(body["approver"]), "", ""], [lab["owner"], _cap(body["owner"]), "", ""]], [4.2, 5.6, 4.0, 2.7])
    note = doc.add_paragraph()
    r = note.add_run(lab["disclaimer"]); r.italic = True; r.font.size = Pt(8.5); r.font.color.rgb = GREY

    doc.add_page_break()
    doc.add_heading(lab["contents"], level=2)
    toc = doc.add_paragraph()
    _field(toc, 'TOC \\o "1-1" \\h \\z \\u', lab["toc_hint"])
    doc.add_paragraph()

    if body.get("template") == "structure":
        n = doc.add_paragraph()
        r = n.add_run(lab["structure_note"]); r.bold = True; r.font.color.rgb = RED

    for s in body["sections"]:
        doc.add_heading(f"{s['number']}. {s['heading']}", level=1)
        for c in s["clauses"]:
            if c.get("table"):
                intro = doc.add_paragraph()
                rn = intro.add_run(f"{c['number']}  "); rn.bold = True
                intro.add_run(c["text"].split(" — ")[0] if " — " in c["text"] else "")
                _table(doc, lab["class_cols"], c["table"], [3.6, 12.9])
                doc.add_paragraph()
                continue
            para = doc.add_paragraph()
            pf = para.paragraph_format
            pf.left_indent = Cm(1.1)
            pf.first_line_indent = Cm(-1.1)
            rn = para.add_run(f"{c['number']}\t"); rn.bold = True; rn.font.color.rgb = ACCENT
            pf.tab_stops.add_tab_stop(Cm(1.1))
            _text_with_placeholders(para, c["text"])

    # Appendix A — open decisions
    doc.add_page_break()
    doc.add_heading(lab["app_a"], level=1)
    if body["open_decisions"]:
        rows = [[i + 1, d["clause_id"], PHT.get(lang, {}).get(d["type"], d["type"]), d["text"], SEV[lang].get(d["severity"], d["severity"])]
                for i, d in enumerate(body["open_decisions"])]
        _table(doc, lab["od_cols"], rows, [0.9, 3.4, 2.6, 7.6, 2.0])
    else:
        doc.add_paragraph(lab["app_a_none"])
    # Appendix B — traceability
    doc.add_heading(lab["app_b"], level=1)
    rows = []
    for s in body["sections"]:
        for c in s["clauses"]:
            basis = lab["basis"].get(c["source_type"], c["source_type"])
            rows.append([f"{c['number']} ({c['clause_id']})", basis, ", ".join(c["source_ids"]) or "—",
                         ", ".join(c["framework_refs"]) or "—",
                         lab["review"].get(c["review_status"], c["review_status"]) + (lab["legal"] if c.get("legal_review") else "")])
    _table(doc, lab["tr_cols"], rows, [3.3, 3.4, 2.8, 4.0, 3.0], font_pt=8)
    # Appendix C — assumptions and gaps
    if body.get("assumptions") or body.get("gaps"):
        doc.add_heading(lab["app_c"], level=1)
        if body.get("assumptions"):
            doc.add_heading(lab["assumptions"], level=2)
            for a in body["assumptions"]:
                doc.add_paragraph(a["text"], style="List Bullet")
        if body.get("gaps"):
            doc.add_heading(lab["gaps"], level=2)
            for g in body["gaps"]:
                doc.add_paragraph(f"{g['clause_id']}: {g['text']}", style="List Bullet")
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


