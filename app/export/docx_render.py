def _report_doc(lang, title, org, subtitle=""):
    doc = _base_document(lang)
    _header_footer(doc, org, lang, date.today().isoformat(), "Internal" if lang == "en" else "Interne")
    doc.add_paragraph(style="Title").add_run(title)
    s = doc.add_paragraph()
    r = s.add_run(f"{org}{'  ·  ' + subtitle if subtitle else ''}  ·  {date.today().isoformat()}")
    r.font.color.rgb = GREY
    _draft_banner(doc, lang)
    doc.add_paragraph()
    return doc


def _save(doc) -> bytes:
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def render_index(org: str, lang: str, rows: list[list[str]]) -> bytes:
    lab = R[lang]
    doc = _report_doc(lang, lab["index"], org)
    doc.add_paragraph(lab["intro_idx"])
    _table(doc, lab["idx_cols"], rows, [3.6, 5.2, 2.2, 2.2, 2.6, 1.3, 2.0], font_pt=8)
    return _save(doc)


def render_decisions(org: str, lang: str, bodies: list[dict], facts: list[list[str]], obligations: list[list[str]],
                     observations: list[dict]) -> bytes:
    lab = R[lang]
    doc = _report_doc(lang, lab["decisions"], org)
    doc.add_paragraph(lab["intro_dec"])
    for b in bodies:
        doc.add_heading(f"{b['policy_id']} — {b['title']}", level=1)
        if b["open_decisions"]:
            _table(doc, L[lang]["od_cols"], [[i + 1, d["clause_id"], PHT.get(lang, {}).get(d["type"], d["type"]), d["text"], SEV[lang][d["severity"]]]
                                             for i, d in enumerate(b["open_decisions"])], [0.9, 3.4, 2.6, 7.6, 2.0], font_pt=8.5)
        else:
            doc.add_paragraph(lab["none"])
    assumptions = {a["key"]: a["text"] for b in bodies for a in b.get("assumptions", [])}
    doc.add_heading(L[lang]["assumptions"], level=1)
    if assumptions:
        for t in assumptions.values():
            doc.add_paragraph(t, style="List Bullet")
    else:
        doc.add_paragraph(lab["none"])
    if observations:
        doc.add_heading(lab["observations"], level=1)
        for o in observations:
            doc.add_paragraph(f"[{SEV[lang][o['severity']]}] {o['text']}", style="List Bullet")
    doc.add_heading(lab["obl"], level=1)
    if obligations:
        _table(doc, lab["obl_cols"], obligations, [7.2, 3.6, 5.7], font_pt=8.5)
    else:
        doc.add_paragraph(lab["none"])
    doc.add_heading(lab["facts"], level=1)
    _table(doc, lab["fact_cols"], facts, [6.0, 7.0, 3.5], font_pt=8.5)
    return _save(doc)


def render_trace(org: str, lang: str, bodies: list[dict]) -> bytes:
    lab = R[lang]
    doc = _report_doc(lang, lab["trace"], org)
    doc.add_paragraph(lab["trace_intro"])
    rows = []
    for b in bodies:
        cl = [c for s in b["sections"] for c in s["clauses"]]
        cnt = lambda k: sum(1 for c in cl if c["source_type"] == k)  # noqa: E731
        rows.append([b["policy_id"], len(cl), cnt("framework_recommendation"), cnt("company_fact"),
                     cnt("organization_decision"), cnt("open_decision"), cnt("confirmed_obligation"),
                     sum(1 for c in cl if c.get("legal_review"))])
    _table(doc, lab["trace_cols"], rows, [3.6, 1.6, 2.0, 2.0, 1.9, 1.6, 2.1, 1.7], font_pt=8.5)
    return _save(doc)


def render_roadmap(org: str, lang: str, bodies: list[dict]) -> bytes:
    lab = R[lang]
    doc = _report_doc(lang, lab["roadmap"], org)
    doc.add_paragraph(lab["gap_intro"])
    rows = [[b["policy_id"], g["clause_id"], g["text"], SEV[lang][g["severity"]]] for b in bodies for g in b.get("gaps", [])]
    if rows:
        _table(doc, lab["gap_cols"], rows, [3.6, 3.2, 7.7, 2.0], font_pt=8.5)
    else:
        doc.add_paragraph(lab["none"])
    return _save(doc)
